"""
Stage 1 - Build the analysis grid and the surface-feature table.

PROVENANCE
----------
REAL        : the analysis grid geometry (1 km cells over the BBMP bounding box,
              EPSG:4326 -> EPSG:32643 for area/metric work), the 8 BBMP zone names,
              the city extent (~800 km2) and the total 2011-census population used
              to scale the population field.
SIMULATED   : every per-cell surface variable (NDVI, built-up fraction, impervious
              fraction, water fraction, tree canopy, albedo, building height) and
              the Land Surface Temperature. These are generated by the model in
              `synthesise_surface()` / `simulate_lst()` below, calibrated so their
              ranges match published Bengaluru summer-daytime observations
              (LST approx. 29.9-48 C, city mean approx. 38.6 C; strong negative
              LST-NDVI and positive LST-NDBI correlations).

NOTHING HERE IS A SATELLITE OBSERVATION. To run on real data, replace
`synthesise_surface()` and `simulate_lst()` with zonal statistics over
Landsat 8/9 ST_B10 (LST) and Sentinel-2 (NDVI/NDWI/NDBI) rasters - the rest of
the pipeline is unchanged.
"""

import json
import math
import numpy as np
import pandas as pd

RNG = np.random.default_rng(20260919)

# --- REAL: BBMP approximate bounding box and zone structure -------------------
LAT_MIN, LAT_MAX = 12.830, 13.140
LON_MIN, LON_MAX = 77.440, 77.780
CELL_KM = 1.0
CITY_AREA_KM2 = 800.0          # BBMP jurisdiction, approx.
CITY_POP_2011 = 8_443_675      # Census 2011, BBMP area
POP_GROWTH = 1.25              # scale to a present-day working estimate

ZONES = [
    # name,                lat,     lon,    radius_km (approx. zone centroid)
    ("Yelahanka",          13.100, 77.596, 7.0),
    ("Dasarahalli",        13.045, 77.513, 5.5),
    ("Mahadevapura",       12.990, 77.710, 8.0),
    ("Bommanahalli",       12.890, 77.625, 7.0),
    ("Rajarajeshwari Nagar", 12.920, 77.500, 8.0),
    ("Bengaluru East",     12.990, 77.640, 6.0),
    ("Bengaluru West",     12.975, 77.545, 6.0),
    ("Bengaluru South",    12.925, 77.585, 6.5),
]

CBD = (12.976, 77.594)   # Vidhana Soudha / city core

FEATURES = [
    "ndvi", "tree_canopy", "builtup", "impervious",
    "water", "albedo", "bldg_height", "elevation",
]


def km(dlat, dlon, lat):
    return math.hypot(dlat * 110.574, dlon * 111.320 * math.cos(math.radians(lat)))


def smooth_field(nr, nc, scale, rng):
    """Spatially autocorrelated random field via iterated box blur."""
    f = rng.standard_normal((nr, nc))
    for _ in range(int(scale)):
        p = np.pad(f, 1, mode="edge")
        f = (p[:-2, 1:-1] + p[2:, 1:-1] + p[1:-1, :-2] + p[1:-1, 2:] + 4 * f) / 8.0
    f -= f.mean()
    s = f.std()
    return f / s if s > 0 else f


def build_grid():
    nr = int(round((LAT_MAX - LAT_MIN) * 110.574 / CELL_KM))
    nc = int(round((LON_MAX - LON_MIN) * 111.320 * math.cos(math.radians(12.98)) / CELL_KM))
    lats = LAT_MIN + (np.arange(nr) + 0.5) * (LAT_MAX - LAT_MIN) / nr
    lons = LON_MIN + (np.arange(nc) + 0.5) * (LON_MAX - LON_MIN) / nc
    return nr, nc, lats, lons


def synthesise_surface(nr, nc, lats, lons):
    """SIMULATED surface characteristics with realistic urban structure."""
    rows = []
    # Independent spatial fields. Each lever needs its own source of variation,
    # otherwise the features end up collinear and any model - linear or otherwise -
    # splits their coefficients arbitrarily, which makes single-lever what-if
    # scenarios meaningless. High NDVI is not the same thing as tree canopy
    # (lawns, parks and cropland are green with no shade), and built-up fraction is
    # not the same thing as sealed surface (car parks, yards, arterial roads).
    core = smooth_field(nr, nc, 6, RNG)
    veg = smooth_field(nr, nc, 5, RNG)
    wet = smooth_field(nr, nc, 4, RNG)
    rough = smooth_field(nr, nc, 3, RNG)
    canopy = smooth_field(nr, nc, 4, RNG)
    seal = smooth_field(nr, nc, 3, RNG)
    refl = smooth_field(nr, nc, 3, RNG)
    hgt = smooth_field(nr, nc, 4, RNG)

    for i in range(nr):
        for j in range(nc):
            lat, lon = lats[i], lons[j]
            d_cbd = km(lat - CBD[0], lon - CBD[1], lat)

            # keep only cells inside the (approximate) BBMP footprint
            inside = False
            zone, zd = None, 1e9
            for name, zlat, zlon, zr in ZONES:
                d = km(lat - zlat, lon - zlon, lat)
                if d <= zr:
                    inside = True
                if d / zr < zd:
                    zd, zone = d / zr, name
            if not inside and d_cbd <= 7.5:
                inside = True          # the core sits between the zone centroids
            if not inside:
                continue

            # urban intensity: high in the core, decaying outward, plus texture
            u = 1.0 / (1.0 + (d_cbd / 12.0) ** 1.7) + 0.18 * core[i, j]
            u = float(np.clip(u, 0.02, 1.0))

            builtup = np.clip(0.12 + 0.70 * u + 0.06 * rough[i, j], 0.03, 0.93)
            impervious = np.clip(0.06 + 0.38 * u + 0.34 * builtup + 0.11 * seal[i, j],
                                 0.02, 0.88)
            ndvi = np.clip(0.52 - 0.42 * u + 0.11 * veg[i, j], 0.04, 0.78)
            tree = np.clip(0.26 * ndvi + 0.085 * canopy[i, j] + 0.10 - 0.05 * u, 0.01, 0.55)
            water = np.clip(0.035 * math.exp(1.6 * wet[i, j]) - 0.012, 0.0, 0.22)
            albedo = np.clip(0.165 + 0.035 * (1 - u) + 0.030 * refl[i, j], 0.09, 0.32)
            height = np.clip(4.0 + 10.5 * u ** 1.2 + 5.5 * hgt[i, j]
                             + 1.2 * rough[i, j], 3.0, 34.0)
            # Bengaluru sits on a plateau around 900 m; the real intra-city span
            # is roughly 840-960 m, rising gently to the north.
            elev = 900 + 21 * core[i, j] - 5 * wet[i, j] + 300 * (lat - 12.98)

            rows.append(dict(
                row=i, col=j, lat=round(float(lat), 5), lon=round(float(lon), 5),
                zone=zone, dist_cbd_km=round(d_cbd, 2), urban_intensity=round(u, 4),
                ndvi=round(float(ndvi), 4), tree_canopy=round(float(tree), 4),
                builtup=round(float(builtup), 4), impervious=round(float(impervious), 4),
                water=round(float(water), 4), albedo=round(float(albedo), 4),
                bldg_height=round(float(height), 2), elevation=round(float(elev), 1),
            ))
    return pd.DataFrame(rows)


def simulate_lst(df):
    """
    SIMULATED Land Surface Temperature (summer daytime, degrees C).

    Energy-balance-flavoured surrogate, NOT a radiative transfer model. Chosen so
    that (a) the marginal effects have the sign and rough magnitude reported in the
    Bengaluru UHI literature, and (b) the ML stage has genuine work to do: the
    relationship is non-linear, has an interaction term, and carries both spatially
    correlated and independent noise.
    """
    n = len(df)
    ndvi_s = (df.ndvi - 0.04) / 0.74
    lst = (
        34.6
        + 13.0 * df.builtup ** 1.6                          # accelerating above ~60% built
        + 5.5 * df.impervious
        - 11.0 * (1 - np.exp(-3.2 * ndvi_s))                # vegetation cooling saturates
        - 7.5 * df.tree_canopy
        - 7.5 * np.sqrt(df.water)
        - 30.0 * (df.albedo - 0.16) * (0.35 + 0.95 * df.builtup)   # roofs only help where roofs exist
        + 2.4 * (df.bldg_height / 30.0) * df.builtup ** 2   # street-canyon trapping
        - 0.0045 * (df.elevation - 900.0)
    )
    nr, nc = df.row.max() + 1, df.col.max() + 1
    field = smooth_field(int(nr), int(nc), 4, RNG)
    lst = lst + 1.55 * field[df.row.values, df.col.values]   # unobserved local drivers
    lst = lst + RNG.normal(0, 0.95, n)                       # sensor / retrieval noise
    # Documented affine calibration so the synthetic field reproduces the published
    # Bengaluru summer-daytime statistics (city mean ~38.6 C, observed span ~29.9-48 C).
    lst = 38.6 + (lst - lst.mean()) * 0.82
    return np.clip(lst, 29.6, 48.2)


def add_population(df):
    """SIMULATED population distribution, scaled to the real BBMP census total."""
    w = (df.builtup ** 1.9) * (1.0 / (1.0 + (df.dist_cbd_km / 11.0) ** 2))
    w = w * np.exp(RNG.normal(0, 0.42, len(df)))
    pop = w / w.sum() * CITY_POP_2011 * POP_GROWTH
    df["population"] = pop.round(0).astype(int)
    df["pop_density"] = df.population / (CELL_KM ** 2)
    # vulnerability proxy: crowding + no nearby green + low building quality signal
    v = (0.45 * _mm(np.log1p(df.pop_density))
         + 0.35 * (1 - _mm(df.ndvi))
         + 0.20 * _mm(df.impervious))
    df["vulnerability"] = v.round(4)
    return df


def _mm(s):
    s = np.asarray(s, dtype=float)
    return (s - s.min()) / (s.max() - s.min() + 1e-9)


def make_wards(df, per_zone=5):
    """
    Split each BBMP zone into contiguous analysis wards by angular sector.
    These are ANALYSIS UNITS, not BBMP's 198 statutory wards - swap in the real
    ward GeoJSON and this function disappears.
    """
    labels = []
    for zone, g in df.groupby("zone"):
        clat, clon = g.lat.mean(), g.lon.mean()
        ang = np.arctan2(g.lat - clat, g.lon - clon)
        rad = np.hypot(g.lat - clat, g.lon - clon)
        k = np.digitize(ang, np.linspace(-np.pi, np.pi, per_zone + 1)[1:-1])
        k = np.where(rad < rad.quantile(0.22), per_zone - 1, k)
        for idx, kk in zip(g.index, k):
            labels.append((idx, f"{zone} W{int(kk) + 1}"))
    s = pd.Series(dict(labels))
    df["ward"] = s.reindex(df.index)
    return df


if __name__ == "__main__":
    nr, nc, lats, lons = build_grid()
    df = synthesise_surface(nr, nc, lats, lons)
    df["lst"] = simulate_lst(df).round(2)
